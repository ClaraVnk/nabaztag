void sim_run_events(void)
{
  for(int i = 0; i < sim.nb_events; i++) {
    struct sim_event *e = &sim.events[i];
    if(e->fired || e->rel_fetch || sim_now() < e->at_ms) continue;
    e->fired = 1;
    switch(e->kind) {
      case SIM_EV_DEAUTH:     vap_deauth(e->ap, 0, (uint16_t)e->arg); break;
      case SIM_EV_DEAUTH_PROT: vap_deauth_protected(e->ap, 0, (uint16_t)e->arg); break;
      case SIM_EV_DISASSOC:   vap_deauth(e->ap, 1, (uint16_t)e->arg); break;
      case SIM_EV_AP_DOWN:    vap_set_up(e->ap, 0); break;
      case SIM_EV_AP_UP:      vap_set_up(e->ap, 1); break;
      case SIM_EV_AP_SECURITY:
        sim.aps[e->ap].security = e->arg;
        vap_restart(e->ap);
        break;
      case SIM_EV_AP_RESTART:   vap_restart(e->ap); break;
      case SIM_EV_AP_FORGET:    vap_forget(e->ap); if(e->arg) vap_mute(e->ap); break;
      case SIM_EV_SERVER_DROP:  gw_server_drop(); break;
      case SIM_EV_SERVER_CLOSE: gw_server_close(1); break;
      case SIM_EV_SERVER_VANISH: gw_server_vanish(); break;
      case SIM_EV_EXPECT_REASSOC:
        if(sim.run_entries >= e->arg)
          sim_log("ok   reached RUN %d time%s, at least %d expected",
                  sim.run_entries, sim.run_entries == 1 ? "" : "s", e->arg);
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected RUN to have been reached %d times, it was %d",
                   e->arg, sim.run_entries);
          sim_note_failure(why);
        }
        break;
      case SIM_EV_EXPECT_XMPP:
        if((int)gw_stats.xmpp_opened >= e->arg)
          sim_log("ok   %u connection%s opened to the XMPP port, at least %d expected",
                  gw_stats.xmpp_opened, gw_stats.xmpp_opened == 1 ? "" : "s", e->arg);
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected %d connections to the XMPP port, there were %u",
                   e->arg, gw_stats.xmpp_opened);
          sim_note_failure(why);
        }
        break;
      case SIM_EV_ARP:         gw_set_arp(e->arg); break;
      case SIM_EV_PTK_REKEY:  vap_ptk_rekey(e->ap); break;
      case SIM_EV_REKEY:      vap_rekey(e->ap); break;
      case SIM_EV_REAUTH:     vap_reauth(e->ap); break;
      case SIM_EV_DROP_EAPOL: vap_drop_eapol(e->arg); break;
      case SIM_EV_UPLOAD:
        phone_start_upload();
        break;
      case SIM_EV_BUTTON:      hw_press(2, e->arg); break;
      case SIM_EV_RFID:
        hw_clear_tags();
        if(e->arg) hw_present_tag(e->tag);
        else sim_log("rfid: the tag was taken away");
        break;
      case SIM_EV_EXPECT_FLASH:
        if((int)hw_flash_writes() >= e->arg)
          sim_log("ok   flashFirmware reached %u time%s with a %d-byte image, at least %d expected",
                  hw_flash_writes(), hw_flash_writes() == 1 ? "" : "s",
                  hw_flash_last_size(), e->arg);
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected flashFirmware to be reached %d time%s, it was %u",
                   e->arg, e->arg == 1 ? "" : "s", hw_flash_writes());
          sim_note_failure(why);
        }
        break;
      case SIM_EV_EXPECT_NO_RESET:
        if(sim.resets == 0)
          sim_log("ok   the firmware never asked for a reset");
        else {
          char why[160];
          snprintf(why, sizeof(why), "the firmware asked for a reset %d time%s (last reason %d%s)",
                   sim.resets, sim.resets == 1 ? "" : "s", sim.last_reset_reason,
                   sim.last_reset_reason == 1 ? ", the VM ran out of memory" : "");
          sim_note_failure(why);
        }
        break;
      case SIM_EV_INJECT_PLAIN: vap_inject_plain(e->ap, e->arg); break;
      case SIM_EV_INJECT_PROBE: vap_inject_probe((uint32_t)e->arg); break;
      case SIM_EV_DHCP_ROGUE: gw_dhcp_rogue(0x0a090909u); break;  /* 10.9.9.9 */
      case SIM_EV_FORGED_MSG1:
      case SIM_EV_RESEND_MSG3:
      case SIM_EV_EAPOL_OVERSIZED:
      case SIM_EV_EXPECT_PTK_INSTALLS:
      case SIM_EV_EXPECT_GROUP_INSTALLS:
      case SIM_EV_EXPECT_PTK_SYNCED:
      case SIM_EV_EXPECT_EAPOL_BADLEN:
      case SIM_EV_EXPECT_TKIP_REFUSED:
      case SIM_EV_EXPECT_SAE_REFUSED:
      case SIM_EV_AP_DATA:
      case SIM_EV_AP_REPLAY:
      case SIM_EV_EXPECT_REPLAY:
      case SIM_EV_EXPECT_DATA_UP:
        sim_audit_event(e); break;
      case SIM_EV_HTTP_BIG: gw_http_big_set((uint32_t)e->arg); break;
      case SIM_EV_HTTP_BIGHEAD: gw_http_big_head_set((uint32_t)e->arg); break;
      case SIM_EV_EXPECT_PLAIN_DROPPED:
        if(ieee80211_plain_dropped >= e->arg)
          sim_log("ok   %u plaintext data frame(s) refused on the protected "
                  "link, at least %d expected", ieee80211_plain_dropped, e->arg);
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected at least %d plaintext data "
                   "frame(s) refused, the rabbit refused %u",
                   e->arg, ieee80211_plain_dropped);
          sim_note_failure(why);
        }
        break;
      case SIM_EV_EXPECT_STATE:
        if(ieee80211_state == e->arg)
          sim_log("ok   state is %s, as expected", sim_state_name(e->arg));
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected state %s, found %s",
                   sim_state_name(e->arg), sim_state_name(ieee80211_state));
          sim_note_failure(why);
        }
        break;
      case SIM_EV_REFUSE_STATE:
        if(ieee80211_state != e->arg)
          sim_log("ok   state is %s, and not %s, as expected",
                  sim_state_name(ieee80211_state), sim_state_name(e->arg));
        else {
          char why[160];
          snprintf(why, sizeof(why), "state must not be %s, but it is",
                   sim_state_name(e->arg));
          sim_note_failure(why);
        }
        break;
      case SIM_EV_EXPECT_SAE:
        if(vap_last_sae_mode == e->arg)
          sim_log("ok   the last SAE commit used %s, as expected",
                  e->arg == 1 ? "hash-to-element" : "hunting and pecking");
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected SAE %s, the AP saw %s",
                   e->arg == 1 ? "hash-to-element" : "hunting and pecking",
                   vap_last_sae_mode == 1 ? "hash-to-element"
                   : vap_last_sae_mode == 2 ? "hunting and pecking" : "no SAE commit at all");
          sim_note_failure(why);
        }
        break;
      default: break;
    }
  }
}

uint8_t nab_boot_button;   /* owner_unlock: main.c's, on a rabbit */

int main(int argc, char **argv)
{
  const char *scenario = NULL;
  const char *eeprom = "rabbit.eeprom";
  const char *audio_dir = NULL;
  const char *warren = NULL;
  const char *gateway_ip = NULL;
  const char *lease_ip = NULL;
  int trace_net = 0;
  int realtime = 0;
  int last_state = -1;
  uint32_t next_timer_ms = 0;
  uint8_t counttimer = 0;

  for(int i = 1; i < argc; i++) {
    if(!strcmp(argv[i], "--eeprom") && i + 1 < argc) eeprom = argv[++i];
    else if(!strcmp(argv[i], "--audio-dir") && i + 1 < argc) audio_dir = argv[++i];
    else if(!strcmp(argv[i], "--no-eeprom")) eeprom = NULL;
    else if(!strcmp(argv[i], "--warren") && i + 1 < argc) warren = argv[++i];
    else if(!strcmp(argv[i], "--gateway-ip") && i + 1 < argc) gateway_ip = argv[++i];
    else if(!strcmp(argv[i], "--lease-ip") && i + 1 < argc) lease_ip = argv[++i];
    else if(!strcmp(argv[i], "--xmpp-port") && i + 1 < argc) gw_set_xmpp_port((uint16_t)atoi(argv[++i]));
    else if(!strcmp(argv[i], "--port80") && i + 1 < argc) gw_set_port80((uint16_t)atoi(argv[++i]));
    else if(!strcmp(argv[i], "--port443") && i + 1 < argc) gw_set_port443((uint16_t)atoi(argv[++i]));
    else if(!strcmp(argv[i], "--upload") && i + 1 < argc) phone_set_upload(argv[++i]);
    else if(!strcmp(argv[i], "--flash-out") && i + 1 < argc) hw_flash_out(argv[++i]);
    else if(!strcmp(argv[i], "--trace-net")) trace_net = 1;
    else if(!strcmp(argv[i], "--realtime")) realtime = 1;
    else if(argv[i][0] == '-') {
      fprintf(stderr,
        "usage: %s [scenario] [--eeprom <file>] [--no-eeprom] [--audio-dir <dir>]\n"
        "\n"
        "  --eeprom      the 4096-byte config page; mkconf.py writes one\n"
        "  --no-eeprom   boot a rabbit straight out of the box\n"
        "  --audio-dir   keep every clip the rabbit plays, as served\n"
        "  --warren      host to send every TCP connection to, port preserved\n"
        "  --gateway-ip  the gateway's address (default 10.0.0.1)\n"
        "  --lease-ip    the address DHCP offers the rabbit (default 10.0.0.42)\n"
        "  --xmpp-port   the warren's XMPP port (default 5222), for the session\n"
        "                bookkeeping and expect-xmpp-opens\n"
        "  --port80      the warren's port that connections to port 80 go to\n"
        "  --port443     the host port that connections to port 443 go to\n"
        "  --upload      the .sim the phone POSTs to the upgrade page of a\n"
        "                rabbit in config mode (scenario: config-mode, upload)\n"
        "  --flash-out   keep the image the rabbit hands to flashFirmware, as the\n"
        "                bytes flash_uc would write (flashsim/ takes it from there)\n"
        "  --trace-net   log every packet, not just what happened to it\n"
        "  --realtime    pace the run to the wall clock, so a server's own\n"
        "                timers line up with the rabbit's life\n",
        argv[0]);
      return 2;
    }
    else scenario = argv[i];
  }

  if(scenario != NULL) {
    if(sim_load(scenario) != 0) return 2;
  } else {
    sim_default();
  }
  /* After the scenario, not before: sim_load starts from sim_default, which
   * zeroes the whole struct, so a flag set while parsing the arguments was
   * wiped and --realtime never paced anything. Found 2026-11-08: a run with
   * the flag still finished 60 s of virtual time in under a second, and a
   * warren whose answer took 28 ms of wall clock was always too late for the
   * rabbit's 10 s of virtual time. */
  if(realtime) sim.realtime = 1;
  if(vap_crypto_selftest() != 0) return 2;
  if(sim.segment) phone_set_segment(sim.segment);
  /* Held before the bytecode's main() reads it: `set master=button2` is the
   * first thing it does, and that one read decides between a station and
   * an access point for the rest of the run. */
  if(sim.config_mode) hw_press(2, 1);
  /* owner_unlock reads the button once at power-on, as main.c does on a
   * rabbit: config mode is the first of its two presses. */
  { extern uint8_t nab_boot_button; nab_boot_button = push_button_value(); }

  sim_log("scenario %s, tick %u ms, stop at %u ms",
          scenario ? scenario : "(default)", sim.tick_ms, sim.stop_ms);

  /* The virtual AP needs the PMK to run a four-way handshake. The rabbit gets
   * its own from the configuration page, where mkconf.py put the PBKDF2 of the
   * same passphrase — so both ends derive it from the scenario and neither is
   * told the other's. Without this the AP reports "no PMK" and a WPA2 run
   * stops in IEEE80211_S_EAPOL with the association already done, which looks
   * like a firmware fault and is not one. */
  if(sim.aps[0].security >= SIM_SEC_WPA_TKIP) {
    /* 40, not 32: mypassword_to_pmk() writes two whole SHA-1 blocks
     * and the firmware's own callers give it 40. ASan found the
     * overrun on 2026-11-08; on macOS it was the abort at exit. */
    uint8_t pmk[40];
    mypassword_to_pmk((const uint8_t *)sim.psk, (uint8_t *)sim.aps[0].ssid,
                      (uint16_t)strlen(sim.aps[0].ssid), pmk);
    vap_set_pmk(pmk);
    sim_log("PMK for \"%s\" / \"%s\": %02x%02x%02x%02x...", sim.aps[0].ssid,
            sim.psk, pmk[0], pmk[1], pmk[2], pmk[3]);
  }

  gw_set_subnet(gateway_ip, lease_ip);
  gw_set_trace(trace_net);
  gw_init(warren);
  hw_eeprom_open(eeprom);
  hw_audio_dir(audio_dir);
  hw_audio_rate(sim.decoder_kbps);

  /* The entropy pool, as main.c starts it; the retained RAM is zeros here. */
  {
    static uint8_t sram[4096];
    uint8_t seed[NAB_RNG_SEED_LEN];
    read_uc_flash(NAB_RNG_SEED_OFF, seed, sizeof seed);
    nab_rng_init(sram, sizeof sram, seed);
    sim_log("rng: pool started, %s seed in the config page",
            nab_rng_seed_stored() ? "a" : "no");
  }

  vap_init();
  ieee80211_init();
  rt2501_driver_install();

  /* From here on it is main.c's sequence, in main.c's order. */
  sim_log("vmemInit");
  vmemInit(0);
  /* Test fixture only: model a rabbit that has handed over to the runtime
     (OPbytecode sets this latch on real hardware). With it set, OPload must
     hide the adoption key and OPsave must refuse -- the key-leak proof runs
     the runtime directly, so there is no bootloader to set it. */
  if (getenv("NAB_FORCE_LATCH")) {
    extern uint8_t nab_kx_latched;
    nab_kx_latched = 1;
    sim_log("NAB_FORCE_LATCH: nab_kx_latched=1 (post-handover model)");
  }
  sim_log("loaderInit");
  loaderInit((uint8_t *)dumpbc);
  sim_log("bytecode loaded: %u functions", _bc_nbfun);

  VPUSH(INTTOVAL(0));
  interpGo();
  (void)VPULL();
  sim_log("the bytecode's main() returned");

  while(sim_now() < sim.stop_ms) {
    struct rt2501buffer *r;

    /* sim_flash_done() comes back to here, from inside interpGo. */
    flash_jmp_armed = 1;
    if(setjmp(flash_jmp)) continue;
    if(cpu_gone) {
      vap_poll();
      phone_poll();
      gw_poll();
      hw_tick();
      while((r = rt2501_receive()) != NULL) hcd_free(r);
      sim_run_events();
      sim_advance(sim.tick_ms);
      sim_pace();
      continue;
    }

    VPUSH(VCALLSTACKGET(_sys_start, SYS_CBLOOP));
    if(VSTACKGET(0) != NIL)
      interpGo();
    (void)VPULL();

    /* Config mode is a press, not a hold: the bootloader reads the button
     * once in main() and then waits for it to be let go, and a button still
     * down 7 s later (TESTDELAY) means the factory test mode instead -- all
     * five lights white, no network. A person lets go when the lights
     * change; this does it a second in. */
    if(sim.config_mode == 1 && sim_now() >= 1000) {
      hw_press(2, 0);
      sim.config_mode = 2;
    }
    vap_poll();
    phone_poll();
    gw_poll();
    hw_tick();

    /* main.c calls these here and again after every frame it takes in, and
     * they are not bookkeeping: play_check() is what moves a sound from the
     * bytecode's FIFO to the decoder. Leave them out and the rabbit fetches
     * its sound, fills the FIFO once and stays silent. */
    play_check(0);
    rec_check();

    while((r = rt2501_receive()) != NULL) {
      sim.data_up++;
      netCb(r->data, r->length, r->source_mac);
      hcd_free(r);
      play_check(0);
      rec_check();
    }

    if(ieee80211_state != last_state) {
      sim_log("state %s -> %s   (radio %d)",
              last_state < 0 ? "-" : sim_state_name(last_state),
              sim_state_name(ieee80211_state), rt2501_state());
      if(ieee80211_state == IEEE80211_S_RUN) sim.run_entries++;
      last_state = ieee80211_state;
    }

    if(sim_now() >= next_timer_ms) {
      next_timer_ms = sim_now() + 100;
      counttimer = (uint8_t)((counttimer + 1) & 3);
      if(!counttimer) rt2501_timer();
    }

    sim_run_events();
    sim_advance(sim.tick_ms);
    sim_pace();
  }

  printf("\n==== run summary ====\n");
  printf("virtual time        %u ms\n", sim_now());
  printf("final state         %s (radio %d)\n",
         sim_state_name(ieee80211_state), rt2501_state());
  printf("frames tx / rx      %u / %u\n", vap_stats.tx_frames, vap_stats.rx_frames);
  printf("data rabbit / AP    %u / %u\n", vap_stats.data_from_sta,
         vap_stats.data_to_sta);
  printf("arp / dhcp / dns    %u / %u / %u\n", gw_stats.arp_requests,
         gw_stats.dhcp_offers, gw_stats.dns_queries);
  if(gw_stats.arp_unanswered)
    printf("  arp left unanswered %u\n", gw_stats.arp_unanswered);
  printf("pings answered      %u\n", gw_stats.pings);
  printf("tcp open/refused    %u / %u (closed %u, xmpp %u)\n", gw_stats.tcp_opened,
         gw_stats.tcp_refused, gw_stats.tcp_closed, gw_stats.xmpp_opened);
  printf("times in RUN        %d\n", sim.run_entries);
  printf("flash writes        %u%s\n", hw_flash_writes(),
         hw_flash_writes() ? "" : " (flashFirmware never reached)");
  if(hw_flash_writes())
    printf("  last image        %d bytes\n", hw_flash_last_size());
  printf("resets asked        %d%s\n", sim.resets,
         sim.resets == 0 ? "" :
         sim.last_reset_reason == 1 ? " (reason 1: the VM ran out of memory)" :
         sim.last_reset_reason == 2 ? " (reason 2: the radio was lost)" :
         sim.last_reset_reason == 3 ? " (reason 3: watchdog)" :
         sim.last_reset_reason == 4 ? " (reason 4: the bytecode asked)" : "");
  if(&nab_verify_calls != NULL)
    printf("verifySig           %d call%s, %d ok, %d out of memory\n",
           nab_verify_calls, nab_verify_calls == 1 ? "" : "s",
           nab_verify_ok, nab_verify_nomem);
  if(phone_stats.uploads_started)
    printf("phone upload        %u bytes in %u segments, answer %d%s\n",
           phone_stats.bytes_sent, phone_stats.segments_sent,
           phone_stats.response_status,
           phone_stats.uploads_finished ? "" : " (not finished)");
  printf("tcp bytes up/down   %u / %u\n", gw_stats.bytes_from_rabbit,
         gw_stats.bytes_to_rabbit);
  sim_replay_summary();
  printf("audio clips played  %u (%u bytes)\n", hw_audio_clips(), hw_audio_bytes());
  printf("ears at count       %u / %u\n", hw_ear_position(0), hw_ear_position(1));
  printf("ear commands        %u / %u\n", hw_ear_commands(0), hw_ear_commands(1));
  for(int i = 0; i < HW_NB_LEDS; i++)
    printf("led %-7s         #%06x\n", hw_led_name(i), hw_led(i));
  printf("failures            %d\n", sim_failures());
  gw_close();
  hw_eeprom_flush();
  return sim_failures() == 0 ? 0 : 1;
}

/*
 * flash_uc does not return on a rabbit: it writes the image and resets. The
 * stub in stubs/hw.c writes nothing, and what comes after a real write is
 * flashsim's subject, not this program's -- so the rabbit simply stops
 * running here. The scenario goes on to its end, so that its expect lines
 * are still evaluated, with nobody home: no bytecode, no frames taken in.
 */
void sim_flash_done(void)
{
  sim_log("flash_uc does not return: the rabbit would write the image and "
          "reset here; the run goes on without it");
  cpu_gone = 1;
  if(flash_jmp_armed) longjmp(flash_jmp, 1);
}

/* The hardware's own reset. A real rabbit comes back from this with its radio
 * asleep, which is why "reboot" on a Nabaztag means pulling the plug. */
void reset_uc(void)
{
  sim.resets++;
  sim.last_reset_reason = nab_reset_reason;
  sim_log("the firmware asked for a processor reset (reason %d%s; heap hp=%d sp=%d, %d of %d words free)",
          nab_reset_reason,
          nab_reset_reason == 1 ? ": the VM ran out of memory" : "",
          _vmem_heapindex, -_vmem_stack,
          VMEM_LENGTH + _vmem_stack - _vmem_heapindex, VMEM_LENGTH);
  hw_eeprom_flush();
  /* A VM that ran out of memory has nothing left to run on: vmemAlloc
   * returns -1 from here on and the bytecode dereferences it. The rabbit
   * reboots at this point; the run stops here, with its summary. */
  if(_vmem_broken) sim.stop_ms = sim_now();
}

/*
 * The signature gate, watched from outside. The Makefile links the VM with
 * -Wl,--wrap=nab_verify_sig (GNU ld only), so every call the OPverifySig
 * case makes lands here first. The scratch buffer -- payload + 64 -- has
 * been allocated by then, so the heap this prints is the most the gate
 * ever holds: what has to fit for an image to be verified at all.
 */
int __real_nab_verify_sig(const uint8_t *payload, size_t payload_len,
                          const uint8_t *sig, void *scratch);
int __wrap_nab_verify_sig(const uint8_t *payload, size_t payload_len,
                          const uint8_t *sig, void *scratch)
{
  int ok;
  sim_log("verifySig gate: %zu-byte payload; heap hp=%d sp=%d, used %d%%, %d of %d words free",
          payload_len, _vmem_heapindex, -_vmem_stack,
          (_vmem_heapindex - _vmem_stack) * 100 / VMEM_LENGTH,
          VMEM_LENGTH + _vmem_stack - _vmem_heapindex, VMEM_LENGTH);
  ok = __real_nab_verify_sig(payload, payload_len, sig, scratch);
  sim_log("verifySig gate: %s", ok ? "signature OK" : "signature refused");
  return ok;
}
