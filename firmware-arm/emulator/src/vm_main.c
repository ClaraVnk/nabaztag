/**
 * @file vm_main.c
 * @brief A whole rabbit: the Metal VM, the Wi-Fi stack, and a virtual AP.
 *
 * The other binary, ./rabbit, drives the 802.11 layer directly. This one
 * starts where a real rabbit starts — at main() — and lets the bytecode do
 * the driving, because on a Nabaztag almost everything is bytecode: the TCP/IP
 * stack is in it (vnet.c is 153 lines and does nothing but pass Ethernet
 * frames up and down), and so are DHCP, DNS, HTTP, XMPP, the choreographies,
 * the ear calibration and the config pages.
 *
 * So this is the rabbit. The VM is nabgcc's, the Wi-Fi is nabgcc's, the
 * bytecode is whatever a warren serves; what the emulator supplies is the
 * hardware underneath — a radio that answers, LEDs and motors that report
 * what they were told, a flash page that remembers, and a clock.
 */
