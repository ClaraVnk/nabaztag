uint32_t counter_timer, counter_timer_s;
volatile uint8_t sim_mmio[1u << 20];

/* The VM's heap. On the hardware this is the external SRAM at 0xD0010000;
 * vmem.h declares it as an array instead when _NAB_SIM is defined. */
int32_t _vmem_heap[VMEM_LENGTH];

/* The bytecode, as a C array. obj/dumpbc.c is generated by mkbc.py from
 * whatever image you point it at, and main.c's own declaration is
 * `extern const uint8_t *dumpbc` with loaderInit() handed its address. */
extern const uint8_t dumpbc[];

void sim_run_events(void)
{
  for(int i = 0; i < sim.nb_events; i++) {
    struct sim_event *e = &sim.events[i];
    if(e->fired || sim_now() < e->at_ms) continue;
    e->fired = 1;
    switch(e->kind) {
      case SIM_EV_DEAUTH:     vap_deauth(e->ap, 0, (uint16_t)e->arg); break;
      case SIM_EV_DISASSOC:   vap_deauth(e->ap, 1, (uint16_t)e->arg); break;
      case SIM_EV_AP_DOWN:    vap_set_up(e->ap, 0); break;
      case SIM_EV_AP_UP:      vap_set_up(e->ap, 1); break;
      case SIM_EV_SERVER_DROP: gw_server_drop(); break;
      case SIM_EV_ARP:         gw_set_arp(e->arg); break;
      case SIM_EV_REKEY:      vap_rekey(e->ap); break;
      case SIM_EV_REAUTH:     vap_reauth(e->ap); break;
      case SIM_EV_DROP_EAPOL: vap_drop_eapol(e->arg); break;
      case SIM_EV_EXPECT_STATE:
        if(ieee80211_state == e->arg)
          sim_log("ok   state is %s, as expected", sim_state_name(e->arg));
        else {
          char why[160];
          snprintf(why, sizeof(why), "expected state %s, found %s",
                   sim_state_name(e->arg), sim_state_name(ieee80211_state));
          sim_note_failure(why);
        }
        break;
      default: break;
    }
  }
}

int main(int argc, char **argv)
{
  const char *scenario = NULL;
  const char *eeprom = "rabbit.eeprom";
  const char *audio_dir = NULL;
  const char *warren = NULL;
  const char *gateway_ip = NULL;
  const char *lease_ip = NULL;
  int trace_net = 0;
  int last_state = -1;
  uint32_t next_timer_ms = 0;
  uint8_t counttimer = 0;

  for(int i = 1; i < argc; i++) {
    if(!strcmp(argv[i], "--eeprom") && i + 1 < argc) eeprom = argv[++i];
    else if(!strcmp(argv[i], "--audio-dir") && i + 1 < argc) audio_dir = argv[++i];
    else if(!strcmp(argv[i], "--no-eeprom")) eeprom = NULL;
    else if(!strcmp(argv[i], "--warren") && i + 1 < argc) warren = argv[++i];
    else if(!strcmp(argv[i], "--gateway-ip") && i + 1 < argc) gateway_ip = argv[++i];
    else if(!strcmp(argv[i], "--lease-ip") && i + 1 < argc) lease_ip = argv[++i];
    else if(!strcmp(argv[i], "--trace-net")) trace_net = 1;
    else if(argv[i][0] == '-') {
      fprintf(stderr,
        "usage: %s [scenario] [--eeprom <file>] [--no-eeprom] [--audio-dir <dir>]\n"
        "\n"
        "  --eeprom      the 4096-byte config page; mkconf.py writes one\n"
        "  --no-eeprom   boot a rabbit straight out of the box\n"
        "  --audio-dir   keep every clip the rabbit plays, as served\n"
        "  --warren      host to send every TCP connection to, port preserved\n"
        "  --gateway-ip  the gateway's address (default 10.0.0.1)\n"
        "  --lease-ip    the address DHCP offers the rabbit (default 10.0.0.42)\n"
        "  --trace-net   log every packet, not just what happened to it\n",
        argv[0]);
      return 2;
    }
    else scenario = argv[i];
  }

  if(scenario != NULL) {
    if(sim_load(scenario) != 0) return 2;
  } else {
    sim_default();
  }
  if(vap_crypto_selftest() != 0) return 2;

  sim_log("scenario %s, tick %u ms, stop at %u ms",
          scenario ? scenario : "(default)", sim.tick_ms, sim.stop_ms);

  /* The virtual AP needs the PMK to run a four-way handshake. The rabbit gets
   * its own from the configuration page, where mkconf.py put the PBKDF2 of the
   * same passphrase — so both ends derive it from the scenario and neither is
   * told the other's. Without this the AP reports "no PMK" and a WPA2 run
   * stops in IEEE80211_S_EAPOL with the association already done, which looks
   * like a firmware fault and is not one. */
  if(sim.aps[0].security >= SIM_SEC_WPA_TKIP) {
    uint8_t pmk[EAPOL_MASTER_KEY_LENGTH];
    mypassword_to_pmk((const uint8_t *)sim.psk, (uint8_t *)sim.aps[0].ssid,
                      (uint16_t)strlen(sim.aps[0].ssid), pmk);
    vap_set_pmk(pmk);
    sim_log("PMK for \"%s\" / \"%s\": %02x%02x%02x%02x...", sim.aps[0].ssid,
            sim.psk, pmk[0], pmk[1], pmk[2], pmk[3]);
  }

  gw_set_subnet(gateway_ip, lease_ip);
  gw_set_trace(trace_net);
  gw_init(warren);
  hw_eeprom_open(eeprom);
  hw_audio_dir(audio_dir);

  vap_init();
  ieee80211_init();
  rt2501_driver_install();

  /* From here on it is main.c's sequence, in main.c's order. */
  sim_log("vmemInit");
  vmemInit(0);
  sim_log("loaderInit");
  loaderInit((uint8_t *)dumpbc);
  sim_log("bytecode loaded: %u functions", _bc_nbfun);

  VPUSH(INTTOVAL(0));
  interpGo();
  (void)VPULL();
  sim_log("the bytecode's main() returned");

  while(sim_now() < sim.stop_ms) {
    struct rt2501buffer *r;

    VPUSH(VCALLSTACKGET(_sys_start, SYS_CBLOOP));
    if(VSTACKGET(0) != NIL)
      interpGo();
    (void)VPULL();

    vap_poll();
    gw_poll();
    hw_tick();

    while((r = rt2501_receive()) != NULL) {
      netCb(r->data, r->length, r->source_mac);
      hcd_free(r);
    }

    if(ieee80211_state != last_state) {
      sim_log("state %s -> %s   (radio %d)",
              last_state < 0 ? "-" : sim_state_name(last_state),
              sim_state_name(ieee80211_state), rt2501_state());
      last_state = ieee80211_state;
    }

    if(sim_now() >= next_timer_ms) {
      next_timer_ms = sim_now() + 100;
      counttimer = (uint8_t)((counttimer + 1) & 3);
      if(!counttimer) rt2501_timer();
    }

    sim_run_events();
    sim_advance(sim.tick_ms);
  }

  printf("\n==== run summary ====\n");
  printf("virtual time        %u ms\n", sim_now());
  printf("final state         %s (radio %d)\n",
         sim_state_name(ieee80211_state), rt2501_state());
  printf("frames tx / rx      %u / %u\n", vap_stats.tx_frames, vap_stats.rx_frames);
  printf("data rabbit / AP    %u / %u\n", vap_stats.data_from_sta,
         vap_stats.data_to_sta);
  printf("arp / dhcp / dns    %u / %u / %u\n", gw_stats.arp_requests,
         gw_stats.dhcp_offers, gw_stats.dns_queries);
  if(gw_stats.arp_unanswered)
    printf("  arp left unanswered %u\n", gw_stats.arp_unanswered);
  printf("pings answered      %u\n", gw_stats.pings);
  printf("tcp open/refused    %u / %u (closed %u)\n", gw_stats.tcp_opened,
         gw_stats.tcp_refused, gw_stats.tcp_closed);
  printf("tcp bytes up/down   %u / %u\n", gw_stats.bytes_from_rabbit,
         gw_stats.bytes_to_rabbit);
  printf("audio clips played  %u (%u bytes)\n", hw_audio_clips(), hw_audio_bytes());
  printf("ears at count       %u / %u\n", hw_ear_position(0), hw_ear_position(1));
  printf("ear commands        %u / %u\n", hw_ear_commands(0), hw_ear_commands(1));
  for(int i = 0; i < HW_NB_LEDS; i++)
    printf("led %-7s         #%06x\n", hw_led_name(i), hw_led(i));
  printf("failures            %d\n", sim_failures());
  gw_close();
  hw_eeprom_flush();
  return sim_failures() == 0 ? 0 : 1;
}

/* The hardware's own reset. A real rabbit comes back from this with its radio
 * asleep, which is why "reboot" on a Nabaztag means pulling the plug. */
void reset_uc(void)
{
  sim_log("the firmware asked for a processor reset");
  hw_eeprom_flush();
}
