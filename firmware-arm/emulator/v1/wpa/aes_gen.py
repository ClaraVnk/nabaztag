"""Writes aes.asm: AES-128 encryption of one block for the PIC18, by hand.

    python3 aes_gen.py > aes.asm

The state is `_aes_s` (16 bytes, access RAM); the 176 bytes of round keys
are C's `rk`, read in order through FSR0. The S-box sits at a 256-byte
boundary in program memory and is read with TBLRD (TBLPTRL = the byte), so
SubBytes is one table read per byte; ShiftRows costs nothing, it only
decides which byte goes where; MixColumns uses xtime on W (rlcf + a
conditional xorlw 0x1b). Nine rounds share one body, the tenth has no
MixColumns. FSR1 and FSR2 (SDCC's stack and frame) are left alone.
"""

SBOX = bytes.fromhex(
    "637c777bf26b6fc53001672bfed7ab76ca82c97dfa5947f0add4a2af9ca472c0"
    "b7fd9326363ff7cc34a5e5f171d8311504c723c31896059a071280e2eb27b275"
    "09832c1a1b6e5aa0523bd6b329e32f8453d100ed20fcb15b6acbbe394a4c58cf"
    "d0efaafb434d338545f9027f503c9fa851a3408f929d38f5bcb6da2110fff3d2"
    "cd0c13ec5f974417c4a77e3d645d197360814fdc222a908846eeb814de5e0bdb"
    "e0323a0a4906245cc2d3ac629195e479e7c8376d8dd54ea96c56f4ea657aae08"
    "ba78252e1ca6b4c6e8dd741f4bbd8b8a703eb5664803f60e613557b986c11d9e"
    "e1f8981169d98e949b1e87e9ce5528df8ca1890dbfe6426841992d0fb054bb16")

out = []
emit = out.append


def sub_shift():
    # new[4c + r] = sbox[old[4((c + r) % 4) + r]], into _aes_t
    for i in range(16):
        c, r = divmod(i, 4)
        src = 4 * ((c + r) % 4) + r
        emit(f"\tmovf\t_aes_s+{src}, W, A")
        emit("\tmovwf\tTBLPTRL, A")
        emit("\ttblrd*")
        emit(f"\tmovff\tTABLAT, _aes_t+{i}")


def xtime():
    emit("\tbcf\tSTATUS, 0, A")
    emit("\trlcf\tWREG, F, A")
    emit("\tbtfsc\tSTATUS, 0, A")
    emit("\txorlw\t0x1b")


def mix_columns():
    # s[k] = a[k] ^ x ^ xtime(a[k] ^ a[k+1]), x = a0 ^ a1 ^ a2 ^ a3
    for c in range(4):
        a = [f"_aes_t+{4 * c + k}" for k in range(4)]
        emit(f"\tmovf\t{a[0]}, W, A")
        for k in (1, 2, 3):
            emit(f"\txorwf\t{a[k]}, W, A")
        emit("\tmovwf\t_aes_x, A")
        for k in range(4):
            emit(f"\tmovf\t{a[k]}, W, A")
            emit(f"\txorwf\t{a[(k + 1) % 4]}, W, A")
            xtime()
            emit("\txorwf\t_aes_x, W, A")
            emit(f"\txorwf\t{a[k]}, W, A")
            emit(f"\tmovwf\t_aes_s+{4 * c + k}, A")


def add_round_key(src):
    for i in range(16):
        emit("\tmovf\tPOSTINC0, W, A")
        emit(f"\txorwf\t{src}+{i}, F, A")


emit("; Generated by aes_gen.py: do not edit.")
emit("\tradix\tdec")
emit("\tinclude\t<p18f6627.inc>")
emit("\tglobal\t_aes_s, _aes_encrypt_asm")
emit("\textern\t_rk")
emit("")
emit("aes_acs\tudata_acs")
emit("_aes_s\tres\t16")
emit("_aes_t\tres\t16")
emit("_aes_x\tres\t1")
emit("_aes_n\tres\t1")
emit("")
emit("aes_code\tcode")
emit("_aes_encrypt_asm:")
emit("\tlfsr\t0, _rk")
emit("\tmovlw\tupper aes_sbox")
emit("\tmovwf\tTBLPTRU, A")
emit("\tmovlw\thigh aes_sbox")
emit("\tmovwf\tTBLPTRH, A")
add_round_key("_aes_s")
emit("\tmovlw\t9")
emit("\tmovwf\t_aes_n, A")
emit("aes_round:")
sub_shift()
mix_columns()
add_round_key("_aes_s")
emit("\tdecfsz\t_aes_n, F, A")
emit("\tbra\taes_round")
sub_shift()
add_round_key("_aes_t")
for i in range(16):
    emit(f"\tmovff\t_aes_t+{i}, _aes_s+{i}")
emit("\treturn\t0")
emit("")
emit("aes_tab\tcode\t0x4000")
emit("aes_sbox:")
for i in range(0, 256, 16):
    emit("\tdb\t" + ", ".join(f"0x{b:02x}" for b in SBOX[i:i + 16]))
emit("\tend")
print("\n".join(out))
