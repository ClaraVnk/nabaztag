#!/usr/bin/env python3
"""Turn a Metal bytecode blob into the C array the VM links against.

The firmware links one bytecode image under the symbol `dumpbc`, and both
main.c and testvm.c hand its address to loaderInit(). A bytecode served over
HTTP by a warren carries a 13-byte ASCII header ("amber" + a version + a
build number) that the boot Metal code strips before calling the `bytecode`
opcode; loaderInit() never sees it. Feed that header to loaderGetInt() and
the globals length reads as 1.7 billion, src walks off the end of the heap
and the VM dies in loaderSizeBC. So strip it here, and prove the parse while
we are at it: a blob whose three section lengths do not add up to its own
size is rejected rather than linked.

  usage: mkbc.py <bytecode> [-o obj/dumpbc.c]
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

MAGIC = b"amber"
HEADER_LENGTH = 13  # "amber" + 4-digit version + 4-digit build


def strip_header(blob: bytes) -> tuple[bytes, str]:
    if blob.startswith(MAGIC):
        return blob[HEADER_LENGTH:], blob[:HEADER_LENGTH].decode("ascii", "replace")
    return blob, ""


def sections(bc: bytes) -> tuple[int, int, int, int]:
    """Re-implement loaderSizeBC, so a bad blob fails here and not at runtime."""
    get_int = lambda o: struct.unpack_from("<i", bc, o)[0]
    get_short = lambda o: struct.unpack_from("<h", bc, o)[0]

    globals_length = get_int(0)
    if not 0 < globals_length < len(bc):
        raise ValueError(f"globals length {globals_length} is not inside a {len(bc)}-byte blob")
    code_length = get_int(globals_length)
    if not 0 <= code_length < len(bc):
        raise ValueError(f"code length {code_length} is not inside a {len(bc)}-byte blob")
    table = globals_length + 4 + code_length
    nbfun = get_short(table)
    total = table + 2 + (nbfun << 2)
    return globals_length, code_length, nbfun, total


def emit(bc: bytes, header: str, source: Path, out: Path) -> None:
    g, c, nbfun, total = sections(bc)
    body = []
    for i in range(0, len(bc), 16):
        body.append("  " + " ".join(f"0x{b:02x}," for b in bc[i : i + 16]))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        f"/* Generated by mkbc.py from {source.name} — do not edit.\n"
        f" * header   {header or '(none)'}\n"
        f" * globals  {g} bytes\n"
        f" * code     {c} bytes\n"
        f" * table    {nbfun} functions\n"
        f" * total    {total} bytes parsed of {len(bc)} present\n"
        f" */\n"
        "#include <stdint.h>\n\n"
        "/* loaderInit() is handed &dumpbc, so the symbol must BE the bytes.\n"
        " * main.c declares it `extern const uint8_t *dumpbc` and takes its\n"
        " * address; an array definition is what makes that agree. */\n"
        f"const uint8_t dumpbc[{len(bc)}] = {{\n" + "\n".join(body) + "\n};\n"
    )
    print(
        f"{out}: {len(bc)} bytes, {g} globals + {c} code + {nbfun} functions "
        f"= {total} parsed ({len(bc) - total} trailing)"
        + (f", header {header}" if header else ""),
        file=sys.stderr,
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("bytecode", type=Path)
    ap.add_argument("-o", "--out", type=Path, default=Path("obj/dumpbc.c"))
    args = ap.parse_args()

    bc, header = strip_header(args.bytecode.read_bytes())
    try:
        emit(bc, header, args.bytecode, args.out)
    except (ValueError, struct.error) as exc:
        print(f"{args.bytecode}: not a Metal bytecode image — {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
