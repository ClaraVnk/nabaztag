"""Print P-256 scalar multiples as C, computed by OpenSSL.

The point of generating these rather than copying them from a document is
the same as in vectors.py: the expected values come from somebody else's
implementation of the same spec. Here that matters more than usual, because
the alternative is a human transcribing 64 hex digits, and a wrong expected
value in a crypto test is worse than no test -- it gets "fixed" by changing
the code until it matches.

Two kinds of vector:

  base   k, then k*G.
  point  k and a, then k*(a*G). OpenSSL is not asked to multiply an
         arbitrary point directly -- its EC point API is not exposed that
         far -- so the expected value comes from ((k*a) mod n)*G, which is
         the same point by associativity. The C code under test does NOT
         take that shortcut: it multiplies the point it is given.
"""
from cryptography.hazmat.primitives.asymmetric import ec

N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551

# Deliberately including the awkward ones: the smallest scalars, a scalar
# with every bit set in the low word, and n-1, whose result is -G.
BASE_K = [1, 2, 3, 4, 7, 0xffffffff, 1 << 128,
          0x7fffffffffffffffffffffffffffffff,
          N - 1,
          0xc9afa9d845ba75166b5c215767b1d6934e50c3db36e89b127b8a622b120f6721]

POINT_KA = [(2, 3), (3, 5), (0xdeadbeef, 7),
            (0x2ca1411a41b17b24cc8c3b089cfd033b1920d5c6e3b54b4d7b4b4f0c6d2d5e8f % N,
             0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296 % N)]


def pt(k: int):
    nums = ec.derive_private_key(k % N, ec.SECP256R1()).public_key().public_numbers()
    return nums.x, nums.y


def hexbytes(v: int) -> str:
    return ", ".join(f"0x{b:02x}" for b in v.to_bytes(32, "big"))


def emit_point(name, x, y):
    print(f"static const uint8_t {name}_x[32] = {{ {hexbytes(x)} }};")
    print(f"static const uint8_t {name}_y[32] = {{ {hexbytes(y)} }};")


print("/* Generated by vectors_p256.py -- do not edit. */")
print("/* Expected values computed by OpenSSL via python-cryptography. */")
print()
print("#ifndef NAB_VECTORS_P256_H")
print("#define NAB_VECTORS_P256_H")
print()
print("#include <stdint.h>")
print()
print("struct p256_base_vec { const uint8_t *k, *x, *y; };")
print("struct p256_point_vec { const uint8_t *k, *px, *py, *x, *y; };")
print()

for i, k in enumerate(BASE_K):
    x, y = pt(k)
    print(f"/* k = {k:#x} */")
    print(f"static const uint8_t bk{i}[32] = {{ {hexbytes(k)} }};")
    emit_point(f"bv{i}", x, y)
    print()

print("static const struct p256_base_vec P256_BASE_VECS[] = {")
for i in range(len(BASE_K)):
    print(f"  {{ bk{i}, bv{i}_x, bv{i}_y }},")
print("};")
print()

for i, (k, a) in enumerate(POINT_KA):
    px, py = pt(a)
    x, y = pt((k * a) % N)
    print(f"/* k = {k:#x} times the point a*G, a = {a:#x} */")
    print(f"static const uint8_t pk{i}[32] = {{ {hexbytes(k)} }};")
    emit_point(f"pp{i}", px, py)
    emit_point(f"pv{i}", x, y)
    print()

print("static const struct p256_point_vec P256_POINT_VECS[] = {")
for i in range(len(POINT_KA)):
    print(f"  {{ pk{i}, pp{i}_x, pp{i}_y, pv{i}_x, pv{i}_y }},")
print("};")
print()
print("#endif")
