"""Print the adoption key-exchange vectors as C (vectors_kx.h).

X25519 and HKDF come from `cryptography`, which is OpenSSL -- independent
of TweetNaCl and of nab_kx.c. The construction on top (salt, info layout,
check bits) is written here from nab_kx.h's description, and is the same
code the warren runs: this file is what holds the two ends together.
"""
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes, serialization

SALT = b"nabaztag adoption v1"


def raw_pub(k):
    return k.public_key().public_bytes(serialization.Encoding.Raw,
                                       serialization.PublicFormat.Raw)


def derive(shared, rabbit_pub, warren_pub):
    okm = HKDF(hashes.SHA256(), 36, SALT, b"nabkx" + rabbit_pub + warren_pub).derive(shared)
    bits = (okm[32] << 8) | okm[33]
    return okm[:32], [(bits >> (3 * (4 - i))) & 7 for i in range(5)]


def c(name, b):
    return f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(f"0x{x:02x}" for x in b) + "};"


out = ["/* Generated by vectors_kx.py -- do not edit. */"]
# RFC 5869 A.1, recomputed by cryptography rather than typed in.
ikm, salt, info = bytes([0x0b] * 22), bytes(range(13)), bytes(range(0xf0, 0xfa))
okm = HKDF(hashes.SHA256(), 42, salt, info).derive(ikm)
out += [c("hk_ikm", ikm), c("hk_salt", salt), c("hk_info", info), c("hk_okm", okm)]

for n in range(3):
    seed_r = bytes((7 * n + i) & 0xff for i in range(32))
    seed_w = bytes((200 - 11 * n + 3 * i) & 0xff for i in range(32))
    r = X25519PrivateKey.from_private_bytes(seed_r)
    w = X25519PrivateKey.from_private_bytes(seed_w)
    rp, wp = raw_pub(r), raw_pub(w)
    shared = r.exchange(w.public_key())
    key, check = derive(shared, rp, wp)
    out += [c(f"kx{n}_rpriv", seed_r), c(f"kx{n}_wpriv", seed_w), c(f"kx{n}_rpub", rp),
            c(f"kx{n}_wpub", wp), c(f"kx{n}_key", key), c(f"kx{n}_check", bytes(check))]
print("\n".join(out))
