"""vectors_chachapoly.h for test_chachapoly.c: ChaCha20-Poly1305 made by
`cryptography` (OpenSSL) for every awkward length -- empty, one byte, one
short of a block, a block, a record -- with and without AAD."""
import os
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305

def arr(name, b):
    print(f"static const uint8_t {name}[] = {{{','.join(str(x) for x in b) or '0'}}};")

print("/* generated by vectors_chachapoly.py -- do not edit */")
cases = []
for i, (n, a) in enumerate([(0, 0), (1, 0), (15, 5), (16, 13), (17, 16), (63, 0), (64, 5),
                            (65, 21), (127, 13), (128, 0), (255, 5), (1000, 5), (4096, 5),
                            (16385, 5)] + [(int.from_bytes(os.urandom(2), "big") % 3000, x % 40) for x in range(50)]):
    key, nonce, pt, aad = os.urandom(32), os.urandom(12), os.urandom(n), os.urandom(a)
    out = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
    for k, v in (("K", key), ("N", nonce), ("P", pt), ("A", aad), ("C", out)):
        arr(f"CP{i}_{k}", v)
    cases.append((i, n, a))
print("static const struct { const uint8_t *k, *n, *p, *a, *c; uint32_t len, alen; } CP[] = {")
for i, n, a in cases:
    print(f"  {{CP{i}_K, CP{i}_N, CP{i}_P, CP{i}_A, CP{i}_C, {n}, {a}}},")
print("};")
