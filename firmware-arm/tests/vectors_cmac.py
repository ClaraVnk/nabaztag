"""Print AES-128 forward-cipher and AES-CMAC vectors as C.

Both come from OpenSSL via python-cryptography: the block cipher so the
encrypt side added for CMAC is checked against FIPS-197 rather than against
its own decrypt side, and CMAC itself so the RFC 4493 cases -- including the
empty message, which is the one every hand-rolled CMAC gets wrong -- come
from somebody else's implementation.

BIP (802.11w) is not here. There is no library call for it, and inventing an
expected value for a MIC would mean deriving it from this code. The test
checks instead the one property that catches the mistake that matters: a
frame whose masked header bits differ must produce the same MIC, and one
whose subtype differs must not.
"""
from cryptography.hazmat.primitives import cmac
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

# RFC 4493's key, and its four message lengths: 0, 16, 40 and 64 bytes.
KEY = bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c")
MSG = bytes.fromhex(
    "6bc1bee22e409f96e93d7e117393172a"
    "ae2d8a571e03ac9c9eb76fac45af8e51"
    "30c81c46a35ce411e5fbc1191a0a52ef"
    "f69f2445df4f9b17ad2b417be66c3710")
LENS = [0, 16, 40, 64]

# A couple more, to exercise the scatter path and a length that is not a
# multiple of the block size.
EXTRA = [(KEY, b"a" * 1), (KEY, b"a" * 15), (KEY, b"a" * 17),
         (bytes(16), bytes(range(100)))]


def arr(name, v):
    body = ", ".join(f"0x{b:02x}" for b in v) if v else "0"
    print(f"static const uint8_t {name}[] = {{ {body} }};")


def mac(key, data):
    c = cmac.CMAC(algorithms.AES(key))
    c.update(data)
    return c.finalize()


print("/* Generated by vectors_cmac.py -- do not edit. */")
print()
print("#ifndef NAB_VECTORS_CMAC_H")
print("#define NAB_VECTORS_CMAC_H")
print()
print("#include <stdint.h>")
print()
print("struct cmac_vec { const uint8_t *key; const uint8_t *msg;")
print("                  uint32_t len; const uint8_t *tag; };")
print()

# The block cipher itself, one FIPS-197 style vector.
enc = Cipher(algorithms.AES(KEY), modes.ECB()).encryptor()
arr("ecb_key", KEY)
arr("ecb_in", MSG[:16])
arr("ecb_out", enc.update(MSG[:16]) + enc.finalize())
print()

arr("cmac_key", KEY)
arr("cmac_msg", MSG)
vecs = []
for i, n in enumerate(LENS):
    arr(f"ct{i}", mac(KEY, MSG[:n]))
    vecs.append(("cmac_key", "cmac_msg", n, f"ct{i}"))
for j, (k, m) in enumerate(EXTRA):
    arr(f"ek{j}", k)
    arr(f"em{j}", m)
    arr(f"et{j}", mac(k, m))
    vecs.append((f"ek{j}", f"em{j}", len(m), f"et{j}"))
print()
print("static const struct cmac_vec CMAC_VECS[] = {")
for key, msg, n, tag in vecs:
    print(f"  {{ {key}, {msg}, {n}, {tag} }},")
print("};")
print()
print("#endif")
