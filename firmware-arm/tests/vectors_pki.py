"""vectors_pki.h for test_pki.c: SHA-384, RSA (PKCS#1 v1.5 and PSS), ECDSA
(P-256, P-384) and two certificate chains, all made by `cryptography`
(OpenSSL) so the firmware's code is checked against an implementation it
shares nothing with. Deterministic keys are not needed: every run makes new
ones and the test only asks that what is valid verifies and what was
tampered with does not."""
import datetime, hashlib
from cryptography import x509
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec, padding

def arr(name, b):
    b = bytes(b)
    body = ",".join(str(x) for x in b) or "0"
    print(f"static const uint8_t {name}[] = {{{body}}};")
    print(f"static const uint32_t {name}_len = {len(b)};")

print("/* generated by vectors_pki.py -- do not edit */")
# SHA-384 around every padding boundary.
lens = [0, 3, 111, 112, 113, 127, 128, 129, 239, 240, 255, 256, 1000]
print("static const uint32_t SHA384_LENS[] = {%s};" % ",".join(map(str, lens)))
msg = bytes((i * 7 + 3) & 0xff for i in range(1000))
arr("SHA384_MSG", msg)
arr("SHA384_OUT", b"".join(hashlib.sha384(msg[:n]).digest() for n in lens))

def pub_n(key):
    return key.public_key().public_numbers().n.to_bytes((key.key_size + 7) // 8, "big")

i = 0
cases = []
for bits in (2048, 3072, 4096):
    k = rsa.generate_private_key(public_exponent=65537, key_size=bits)
    for h, hl in ((hashes.SHA256(), 32), (hashes.SHA384(), 48)):
        m = b"the rabbit trusts this %d %d" % (bits, hl)
        d = hashlib.new(h.name, m).digest()
        for kind in ("pkcs1", "pss"):
            pad = padding.PKCS1v15() if kind == "pkcs1" else padding.PSS(
                mgf=padding.MGF1(h), salt_length=hl)
            sig = k.sign(m, pad, h)
            arr(f"RSA{i}_N", pub_n(k)); arr(f"RSA{i}_S", sig); arr(f"RSA{i}_H", d)
            cases.append((i, kind))
            i += 1
print("static const struct { const uint8_t *n, *s, *h; uint32_t nl, sl, hl; int pss; } RSA_CASES[] = {")
for j, kind in cases:
    print(f"  {{RSA{j}_N, RSA{j}_S, RSA{j}_H, sizeof RSA{j}_N, sizeof RSA{j}_S, sizeof RSA{j}_H, {int(kind == 'pss')}}},")
print("};")

i = 0
ecases = []
for curve, cid in ((ec.SECP256R1(), 0), (ec.SECP384R1(), 1)):
    k = ec.generate_private_key(curve)
    pub = k.public_key().public_bytes(serialization.Encoding.X962,
                                      serialization.PublicFormat.UncompressedPoint)
    for h in (hashes.SHA256(), hashes.SHA384()):
        for rep in range(3):
            m = b"ecdsa %d %s %d" % (cid, h.name.encode(), rep)
            sig = k.sign(m, ec.ECDSA(h))
            arr(f"EC{i}_Q", pub); arr(f"EC{i}_S", sig); arr(f"EC{i}_H", hashlib.new(h.name, m).digest())
            ecases.append((i, cid))
            i += 1
print("static const struct { const uint8_t *q, *s, *h; uint32_t ql, sl, hl; int curve; } EC_CASES[] = {")
for j, cid in ecases:
    print(f"  {{EC{j}_Q, EC{j}_S, EC{j}_H, sizeof EC{j}_Q, sizeof EC{j}_S, sizeof EC{j}_H, {cid}}},")
print("};")

# Certificate chains.
T0 = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
T1 = datetime.datetime(2027, 1, 1, tzinfo=datetime.timezone.utc)
def name(cn): return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
def cert(subject, key, issuer, ikey, h, ca, san=None, extra=None):
    b = (x509.CertificateBuilder().subject_name(name(subject)).issuer_name(name(issuer))
         .public_key(key.public_key()).serial_number(x509.random_serial_number())
         .not_valid_before(T0).not_valid_after(T1)
         .add_extension(x509.BasicConstraints(ca=ca, path_length=None), critical=True))
    if ca:
        b = b.add_extension(x509.KeyUsage(False, False, False, False, False, True, True, False, False), critical=True)
    if san:
        b = b.add_extension(x509.SubjectAlternativeName([x509.DNSName(s) for s in san]), critical=False)
    if extra:
        b = b.add_extension(extra, critical=True)
    return b.sign(ikey, h).public_bytes(serialization.Encoding.DER)

root = rsa.generate_private_key(public_exponent=65537, key_size=4096)
inter_ec = ec.generate_private_key(ec.SECP384R1())
leaf_ec = ec.generate_private_key(ec.SECP256R1())
inter_rsa = rsa.generate_private_key(public_exponent=65537, key_size=2048)
leaf_rsa = rsa.generate_private_key(public_exponent=65537, key_size=2048)
arr("ROOT", cert("Root", root, "Root", root, hashes.SHA384(), True))
arr("INTER_EC", cert("Inter EC", inter_ec, "Root", root, hashes.SHA384(), True))
arr("LEAF_EC", cert("podcast.example.test", leaf_ec, "Inter EC", inter_ec, hashes.SHA384(), False,
                    san=["podcast.example.test", "*.cdn.example.test"]))
arr("INTER_RSA", cert("Inter RSA", inter_rsa, "Root", root, hashes.SHA256(), True))
arr("LEAF_RSA", cert("radio.example.test", leaf_rsa, "Inter RSA", inter_rsa, hashes.SHA256(), False,
                     san=["radio.example.test"]))
arr("LEAF_CRIT", cert("odd.example.test", leaf_ec, "Inter EC", inter_ec, hashes.SHA256(), False,
                      san=["odd.example.test"],
                      extra=x509.UnrecognizedExtension(x509.ObjectIdentifier("1.3.6.1.4.1.99999.1"), b"\x05\x00")))
