"""Build real WPA2 message-3 Key Data fields and print them as C.

PMK -> PTK with IEEE 802.11's PRF-384, KEK = PTK[16:32], then KDEs wrapped
with RFC 3394 — exactly the bytes an access point puts on the wire. Generated
rather than hand-written so the expected values come from somebody else's
implementation of the same specs.
"""
import hashlib
import hmac

from cryptography.hazmat.primitives.keywrap import aes_key_wrap


def prf(key: bytes, label: str, data: bytes, nbits: int) -> bytes:
    out, i = b"", 0
    while len(out) * 8 < nbits:
        out += hmac.new(key, label.encode() + b"\x00" + data + bytes([i]),
                        hashlib.sha1).digest()
        i += 1
    return out[: nbits // 8]


def ptk_of(pmk, aa, spa, anonce, snonce):
    data = min(aa, spa) + max(aa, spa) + min(anonce, snonce) + max(anonce, snonce)
    return prf(pmk, "Pairwise key expansion", data, 384)


def kde(data_type: int, payload: bytes) -> bytes:
    """One KDE. The length byte counts the OUI (3) + the type (1) + payload."""
    return bytes([0xDD, 4 + len(payload), 0x00, 0x0F, 0xAC, data_type]) + payload


def gtk_kde(gtk: bytes, key_index: int) -> bytes:
    return kde(1, bytes([key_index & 0x03, 0x00]) + gtk)


def pad8(b: bytes) -> bytes:
    return b + bytes((-len(b)) % 8)


def carr(name: str, b: bytes) -> str:
    body = ",".join(f"0x{x:02x}" for x in b)
    return f"static const uint8_t {name}[{len(b)}] = {{{body}}};"


pmk = bytes.fromhex(
    "0dc0d6eb90555ed6419756b9a15ec3e3209b63df707dd508d14581f8982721af")
aa = bytes.fromhex("001122334455")
spa = bytes.fromhex("001d92164f1c")
anonce = bytes(range(32))
snonce = bytes(range(32, 64))

ptk = ptk_of(pmk, aa, spa, anonce, snonce)
kek = ptk[16:32]

print("/* Generated by vectors.py. A genuine WPA2 message 3: PMK through")
print(" * IEEE 802.11's PRF-384 to the KEK, then KDEs wrapped per RFC 3394")
print(" * by python-cryptography. Do not edit by hand. */")
print("#include <stdint.h>")
print()
print(carr("V_KEK", kek))

# 1. the ordinary case: one GTK KDE, 128-bit key, index 2
gtk1 = bytes.fromhex("112233445566778899aabbccddeeff00")
plain1 = pad8(gtk_kde(gtk1, 2))
print(carr("V_KEY_DATA", aes_key_wrap(kek, plain1)))
print(carr("V_PLAIN", plain1))
print(carr("V_GTK", gtk1))
print("#define V_KEY_INDEX 2")
print()

# 2. a 256-bit key, behind a KDE of another type the walker must step over
gtk2 = bytes(range(0x40, 0x60))
plain2 = pad8(kde(4, bytes(20)) + gtk_kde(gtk2, 1))
print(carr("V2_KEY_DATA", aes_key_wrap(kek, plain2)))
print(carr("V2_GTK", gtk2))
print("#define V2_KEY_INDEX 1")
