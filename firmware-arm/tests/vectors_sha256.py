"""Print SHA-256, HMAC-SHA-256 and 802.11 KDF vectors as C.

SHA-256 and HMAC come from Python's hashlib and hmac, which are OpenSSL --
an independent implementation of the same FIPS and RFC documents.

The KDF is different and worth being honest about: there is no library call
for 802.11-2020 12.7.1.6.2, so the expected values below come from a Python
implementation written from the standard's text, separately from the C. That
catches a transcription slip in either one. It does NOT catch both of them
misreading the same sentence the same way -- the little-endian counter and
the little-endian length in bits are exactly the kind of detail that would
survive. Interop with a real access point is the only test that settles it,
and that test is the emulator, not this file.
"""
import hashlib
import hmac

MSGS = [
    b"",
    b"abc",
    b"a" * 55,                      # one byte short of needing a second block
    b"a" * 56,                      # exactly at the padding boundary
    b"a" * 64,                      # a whole block
    b"a" * 1000,                    # several blocks, and a partial update path
    bytes(range(256)),
]

HMACS = [
    (b"\x0b" * 20, b"Hi There"),                      # RFC 4231 case 1
    (b"Jefe", b"what do ya want for nothing?"),       # RFC 4231 case 2
    (b"\xaa" * 131, b"Test Using Larger Than Block-Size Key"),
    (b"", b""),
]


def kdf(key: bytes, label: str, context: bytes, nbytes: int) -> bytes:
    """802.11-2020 12.7.1.6.2, KDF-Hash-Length with HMAC-SHA-256."""
    nbits = nbytes * 8
    out, i = b"", 1
    while len(out) < nbytes:
        out += hmac.new(key,
                        i.to_bytes(2, "little") + label.encode() + context
                        + nbits.to_bytes(2, "little"),
                        hashlib.sha256).digest()
        i += 1
    return out[:nbytes]


KDFS = [
    (b"\x01" * 32, "SAE KCK and PMK", b"\x02" * 32, 64),
    (b"key", "Test", b"", 16),
    (b"\xff" * 16, "A longer label than usual", b"\x00\x01\x02", 48),
]


def arr(name, v):
    body = ", ".join(f"0x{b:02x}" for b in v) if v else "0"
    print(f"static const uint8_t {name}[] = {{ {body} }};")


print("/* Generated by vectors_sha256.py -- do not edit. */")
print()
print("#ifndef NAB_VECTORS_SHA256_H")
print("#define NAB_VECTORS_SHA256_H")
print()
print("#include <stdint.h>")
print()
print("struct sha_vec { const uint8_t *msg; uint32_t len; const uint8_t *md; };")
print("struct hmac_vec { const uint8_t *key; uint32_t keylen;")
print("                  const uint8_t *msg; uint32_t msglen; const uint8_t *md; };")
print("struct kdf_vec { const uint8_t *key; uint32_t keylen; const char *label;")
print("                 const uint8_t *ctx; uint32_t ctxlen;")
print("                 const uint8_t *out; uint32_t outlen; };")
print()

for i, m in enumerate(MSGS):
    arr(f"sm{i}", m)
    arr(f"sd{i}", hashlib.sha256(m).digest())
print()
print("static const struct sha_vec SHA256_VECS[] = {")
for i, m in enumerate(MSGS):
    print(f"  {{ sm{i}, {len(m)}, sd{i} }},")
print("};")
print()

for i, (k, m) in enumerate(HMACS):
    arr(f"hk{i}", k)
    arr(f"hm{i}", m)
    arr(f"hd{i}", hmac.new(k, m, hashlib.sha256).digest())
print()
print("static const struct hmac_vec HMAC256_VECS[] = {")
for i, (k, m) in enumerate(HMACS):
    print(f"  {{ hk{i}, {len(k)}, hm{i}, {len(m)}, hd{i} }},")
print("};")
print()

for i, (k, label, ctx, n) in enumerate(KDFS):
    arr(f"kk{i}", k)
    arr(f"kc{i}", ctx)
    arr(f"ko{i}", kdf(k, label, ctx, n))
    print(f'static const char kl{i}[] = "{label}";')
print()
print("static const struct kdf_vec KDF_VECS[] = {")
for i, (k, label, ctx, n) in enumerate(KDFS):
    print(f"  {{ kk{i}, {len(k)}, kl{i}, kc{i}, {len(ctx)}, ko{i}, {n} }},")
print("};")
print()
print("#endif")
