"""Print the TLS vectors as C (vectors_tls.h).

Two kinds. The PSK derivation (nab_tls_psk) is recomputed here with
hashlib/hmac from RFC 5869's text -- the same two lines the warren's kx.py
runs. The session is a recording: `tls_client --dump` against
`openssl s_server` (tls_interop.py keeps it as openssl-short.dump), every
byte each side sent, in order. With a fixed client random and no (EC)DHE
the client's key schedule is a function of the server's bytes alone, so
test_tls.c replays the server's lines and must reproduce the client's
lines byte for byte: the ClientHello, the Finished, the application record
and the close_notify, as OpenSSL accepted them.

  python3 vectors_tls.py openssl-short.dump > vectors_tls.h
"""
import hashlib
import hmac
import sys

PSK_SALT = b"nabaztag tls v1"
PSK_INFO = b"nabtls psk"


def hkdf(length, salt, ikm, info):
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    out, t, i = b"", b"", 0
    while len(out) < length:
        i += 1
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
    return out[:length]


def c(name, b):
    return (f"static const uint8_t {name}[{len(b)}] = {{"
            + ",".join(f"0x{x:02x}" for x in b) + "};")


def main():
    out = ["/* Generated by vectors_tls.py -- do not edit. */"]
    for n, key in enumerate((bytes(range(32)), bytes(0x80 + i for i in range(32)),
                             hashlib.sha256(b"third").digest())):
        out.append(c(f"psk{n}_key", key))
        out.append(c(f"psk{n}_psk", hkdf(32, PSK_SALT, key, PSK_INFO)))

    lines = [l.strip() for l in open(sys.argv[1]) if l.strip()]
    out.append(f"#define SESSION_LINES {len(lines)}")
    out.append("static const struct { char dir; const uint8_t *p; uint32_t n; } session[] = {")
    arrays = []
    for i, l in enumerate(lines):
        b = bytes.fromhex(l[1:])
        arrays.append(c(f"s{i}", b))
        out.append(f"  {{ '{l[0]}', s{i}, {len(b)} }},")
    out.append("};")
    print("\n".join(out[:7] + arrays + out[7:]))


if __name__ == "__main__":
    main()
